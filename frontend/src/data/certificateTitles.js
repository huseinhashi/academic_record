// Helper function to get all degree levels
export const getDegreeLevels = () => {
  return Object.keys(CERTIFICATE_TITLES);
};

// Helper function to get titles for a specific degree level and field
export const getTitlesForDegreeAndField = (degreeLevel, field) => {
  return CERTIFICATE_TITLES[degreeLevel]?.[field] || [];
};

// Helper function to get all titles for a degree level
export const getAllTitlesForDegree = (degreeLevel) => {
  const titles = [];
  const fields = CERTIFICATE_TITLES[degreeLevel] || {};
  
  Object.values(fields).forEach(fieldTitles => {
    titles.push(...fieldTitles);
  });
  
  return titles;
};
